"""Reproduce the Diamond EPICS templates and CSS BOY displays (Python 3.6+)."""
from pathlib import Path
import copy
import uuid
import xml.etree.ElementTree as ET

DRIVER = Path(__file__).resolve().parents[1]
MAIN = DRIVER.parents[1]
DB = MAIN / 'epics/PCF0CoreApp/Db'
BOY = MAIN / 'boy/mimics'

# (name, EPICS numeric representation, minimum, maximum)
GLOBALS = [('GateTicks', 'double', 3200, 4294967295),
           ('ScopeHoldOffTicks', 'double', 0, 4294967295),
           ('TriggerReset', 'int', 0, 1), ('ClearLossCounters', 'int', 0, 1)]
CONTROLS = [('Start', 'int', 0, 1), ('Threshold', 'int', -2147483648, 2147483647),
            ('TailTicks', 'int', 0, 65535), ('BaselineHold', 'int', 0, 1),
            ('MaxLength', 'double', 0, 4294967295),
            ('PeakMin', 'int', '$(MIN_LO=-2147483648)', '$(MIN_HI=2147483647)'),
            ('PeakShift', 'int', 0, 31),
            ('IntegralMin', 'int', '$(MIN_LO=-2147483648)', '$(MIN_HI=2147483647)'),
            ('IntegralShift', 'int', 0, 31), ('ScopeEnable', 'int', 0, 1),
            ('RawEnable', 'int', 0, 1), ('ScopePreTicks', 'int', 0, 248),
            ('ScopeRecordTicks', 'int', 1, 65532)]
RATES = ['MeasuredRate', 'CorrectedRate', 'CorrectedRate2', 'DeadFraction', 'PileUpFraction']
DIAGNOSTICS = ['RateGateGaps', 'SpectrumGateGaps', 'SpectrumBadBlocks', 'SpectrumBadWords', 'ScopeBadWords']
LOSSES = ['RawLost', 'PulseLost', 'RateLost', 'SpecLost', 'ScopeLost']

def record(kind, name, fields):
    return 'record({}, "$(P){}") {{\n'.format(kind, name) + ''.join(
        '    field({}, "{}")\n'.format(k, v) for k, v in fields) + '}\n\n'

def scalar(name, floating=False, output=False, lo=None, hi=None, pushed=False):
    kind = ('ao' if output else 'ai') if floating else ('longout' if output else 'longin')
    fields = [('DTYP', 'asynFloat64' if floating else 'asynInt32'),
              ('OUT' if output else 'INP', '@asyn($(PORT),0)' + name)]
    if output:
        if lo is not None: fields += [('DRVL', lo), ('DRVH', hi)]
    else:
        fields += [('SCAN', 'I/O Intr' if pushed else '1 second')]
    return record(kind, name, fields)

def waveform(name, dtype, count, pushed=True):
    dtyp, ftvl = {'i16': ('asynInt16ArrayIn', 'SHORT'), 'i32': ('asynInt32ArrayIn', 'LONG'),
                  'double': ('asynFloat64ArrayIn', 'DOUBLE')}[dtype]
    return record('waveform', name, [('DTYP', dtyp), ('INP', '@asyn($(PORT),0)' + name),
        ('SCAN', 'I/O Intr' if pushed else '1 second'), ('FTVL', ftvl), ('NELM', count)])

def write_templates():
    root = '# Generated by tools/generate_ioc_ui.py. Macros P, PORT. No automatic writes at IOC startup.\n\n'
    root += scalar('StateMachine-setState', output=True)
    for n in ['StateMachine-getState', 'StateMachine-getGlobalState', 'Status', 'Acquiring', 'WorkerFault']:
        root += scalar(n)
    for n, t, lo, hi in GLOBALS:
        root += scalar(n, t == 'double', True, lo, hi) + scalar(n + '_RBV', t == 'double')
    root += waveform('DeviceConfig', 'i32', 8, False)
    ch = '# Generated by tools/generate_ioc_ui.py. Macros P, PORT, CH, MIN_LO, MIN_HI.\n\n'
    for n, t, lo, hi in CONTROLS:
        name = n + '_Ch$(CH)'
        ch += scalar(name, t == 'double', True, lo, hi) + scalar(name + '_RBV', t == 'double')
    for n in ['Run', 'Baseline', 'SpecOverrun']:
        ch += scalar(n + '_Ch$(CH)', n == 'SpecOverrun')
    for n in LOSSES:
        ch += waveform(n + '_Ch$(CH)', 'i32', 2, False)
        ch += scalar(n + '_Ch$(CH)_Display', True)
    for n in RATES + DIAGNOSTICS:
        ch += scalar(n + '_Ch$(CH)', True, pushed=True)
    for n, dtype, count in [('RawData', 'i16', 262144), ('ScopeData', 'i16', 262144),
                            ('PulseRecords', 'i32', 524288), ('RateRecords', 'i32', 524288),
                            ('SpectrumHeader', 'i32', 8), ('ScopeHeader', 'i32', 8),
                            ('PeakSpectrum', 'double', 512), ('IntegralSpectrum', 'double', 1024)]:
        ch += waveform(n + '_Ch$(CH)', dtype, count)
    for path in [DRIVER / 'db', DB]:
        path.mkdir(parents=True, exist_ok=True)
        (path / 'DiamondDetectorDAQ.template').write_text(root, encoding='utf-8')
        (path / 'DiamondDetectorDAQ-channel.template').write_text(ch, encoding='utf-8')
    subs = 'file "DiamondDetectorDAQ.template" {\n    pattern { P, PORT }\n'
    for b in [0, 2]: subs += '    {{ "D1-I2-HWCF:B-{}-", "B-{}" }}\n'.format(b, b)
    subs += '}\nfile "DiamondDetectorDAQ-channel.template" {\n    pattern { P, PORT, CH, MIN_LO, MIN_HI }\n'
    for b in [0, 2]:
        for c in [0, 1]:
            lo, hi = (-2147483648, 2147483647) if c == 0 else (-32768, 32767)
            subs += '    {{ "D1-I2-HWCF:B-{}-", "B-{}", "{}", "{}", "{}" }}\n'.format(b, b, c, lo, hi)
    (DB / 'DiamondDetectorDAQ.substitutions').write_text(subs + '}\n', encoding='utf-8')

def put(parent, name, value):
    node = parent.find(name)
    if node is None: node = ET.SubElement(parent, name)
    node.text = str(value)
    return node

def display(name, width, height, macros=None):
    d = ET.Element('display', typeId='org.csstudio.opibuilder.Display', version='1.0.0')
    for k, v in [('name', name), ('width', width), ('height', height), ('boy_version', '5.1.0'),
                 ('show_grid', 'false'), ('widget_type', 'Display')]: put(d, k, v)
    ET.SubElement(ET.SubElement(d, 'background_color'), 'color', red='238', green='242', blue='246')
    m = ET.SubElement(d, 'macros'); put(m, 'include_parent_macros', 'true')
    for k, v in (macros or {}).items(): put(m, k, v)
    return d

SAMPLES = None
GRAPH = None
def widget(parent, kind, x, y, width, height, text='', pv=''):
    w = copy.deepcopy(SAMPLES[kind])
    for k, v in [('x', x), ('y', y), ('width', width), ('height', height), ('name', text or pv),
                 ('text', text), ('auto_size', 'false'), ('horizontal_alignment', 0),
                 ('transparent', 'false'), ('wrap_words', 'false')]: put(w, k, v)
    if pv: put(w, 'pv_name', pv)
    put(w, 'tooltip', pv or text)
    font = w.find('font')
    if font is not None:
        font.clear(); ET.SubElement(font, 'opifont.name', fontName='DejaVu Sans', height='11', style='0', pixels='false')
    for name in ['rules', 'scripts', 'actions']:
        node = w.find(name)
        if node is not None: node.clear()
    parent.append(w)
    put(w, 'wuid', str(uuid.uuid5(uuid.NAMESPACE_URL, parent.findtext('name', '') + kind + str(x) + ':' + str(y))))
    return w

def label(d, text, x, y, width=320): return widget(d, 'Label', x, y, width, 28, text)
def value(d, pv, x, y, width=140): return widget(d, 'TextUpdate', x, y, width, 28, pv=pv)
def button(d, text, x, y, pv=None, val=None, path=None, macros=None, width=125):
    w = widget(d, 'ActionButton', x, y, width, 34, text)
    actions = w.find('actions'); actions.set('hook_all', 'false'); actions.set('hook', 'false')
    a = ET.SubElement(actions, 'action', type='WRITE_PV' if pv else 'OPEN_DISPLAY')
    if pv:
        put(a, 'pv_name', pv); put(a, 'value', val); put(a, 'timeout', 10)
    else:
        put(a, 'path', path); put(a, 'mode', 0)
        m = ET.SubElement(a, 'macros'); put(m, 'include_parent_macros', 'true')
        for k, v in (macros or {}).items(): put(m, k, v)
    put(a, 'description', text)
    return w

def graph(d, title, pv, x, y, width, height, count, x_title):
    w = copy.deepcopy(GRAPH)
    for child in list(w):
        if child.tag.startswith('trace_1_'): w.remove(child)
    for k, v in [('x', x), ('y', y), ('width', width), ('height', height), ('title', title),
                 ('trace_count', 1), ('trace_0_y_pv', pv), ('trace_0_name', title),
                 ('trace_0_buffer_size', count), ('trace_0_line_width', 1),
                 ('axis_0_axis_title', x_title), ('axis_1_axis_title', 'ADC code' if 'Data' in pv else 'Counts / gate'),
                 ('show_toolbar', 'true'), ('show_legend', 'false'), ('name', title)]: put(w, k, v)
    d.append(w)
    put(w, 'wuid', str(uuid.uuid5(uuid.NAMESPACE_URL, d.findtext('name', '') + title + str(x) + ':' + str(y))))

def write_xml(path, root):
    # ET.indent is not available on the older Python shipped by some CODAC hosts.
    import xml.dom.minidom
    text = xml.dom.minidom.parseString(ET.tostring(root)).toprettyxml(indent='  ', encoding='UTF-8')
    path.write_bytes(text)

